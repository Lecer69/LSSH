//! Shell completion scripts, generated from the command table. Server names
//! are looked up at completion time with `lssh list --names`.

use anyhow::{Result, bail};

use crate::cli::{COMMANDS, Complete, Spec};

pub fn script(shell: &str) -> Result<String> {
    Ok(match shell {
        "bash" => bash(),
        "zsh" => zsh(),
        "fish" => fish(),
        _ => bail!("unsupported shell '{shell}'\nsupported shells: bash, zsh, fish"),
    })
}

/// Every name and alias of `spec`.
fn names(spec: &Spec) -> Vec<&'static str> {
    std::iter::once(spec.name).chain(spec.alias).collect()
}

fn all_command_words() -> String {
    COMMANDS
        .iter()
        .flat_map(names)
        .collect::<Vec<_>>()
        .join(" ")
}

fn option_words(spec: &Spec) -> String {
    let mut words = Vec::new();
    for opt in spec.options {
        words.push(opt.long.to_string());
        if let Some(short) = opt.short {
            words.push(format!("-{short}"));
        }
    }
    words.push("--help".to_string());
    words.join(" ")
}

fn connect_spec() -> &'static Spec {
    COMMANDS
        .iter()
        .find(|spec| spec.name == "connect")
        .expect("connect is in the command table")
}

fn bash() -> String {
    let mut option_cases = String::new();
    let mut argument_cases = String::new();
    for spec in COMMANDS {
        let pattern = names(spec).join("|");
        option_cases.push_str(&format!(
            "            {pattern}) opts=\"{}\" ;;\n",
            option_words(spec)
        ));
        let action = match spec.completes {
            Complete::Nothing => continue,
            Complete::Server => "[[ $COMP_CWORD -eq 2 ]] && COMPREPLY=($(compgen -W \"$(_lssh_servers)\" -- \"$cur\"))".to_string(),
            Complete::Servers => "[[ $COMP_CWORD -eq 2 ]] && _lssh_server_list".to_string(),
            Complete::RemotePath => "_lssh_remote_path".to_string(),
            Complete::File => "COMPREPLY=($(compgen -f -- \"$cur\"))".to_string(),
            Complete::Command => format!(
                "[[ $COMP_CWORD -eq 2 ]] && COMPREPLY=($(compgen -W \"{}\" -- \"$cur\"))",
                all_command_words()
            ),
            Complete::Choices(choices) => format!(
                "[[ $COMP_CWORD -eq 2 ]] && COMPREPLY=($(compgen -W \"{}\" -- \"$cur\"))",
                choices.join(" ")
            ),
        };
        argument_cases.push_str(&format!("        {pattern}) {action} ;;\n"));
    }

    format!(
        r#"# bash completion for lssh (generated by `lssh completions bash`)

_lssh_servers() {{
    lssh list --names 2>/dev/null
}}

# A comma-separated list of servers, or "all".
_lssh_server_list() {{
    local prefix="" all="all"
    if [[ $cur == *,* ]]; then
        prefix="${{cur%,*}},"
        all=""
    fi
    COMPREPLY=($(compgen -P "$prefix" -W "$(_lssh_servers) $all" -- "${{cur##*,}}"))
}}

# <server>:<path> or a local path.
_lssh_remote_path() {{
    COMPREPLY=($(compgen -W "$(_lssh_servers | sed 's/$/:/')" -- "$cur") $(compgen -f -- "$cur"))
    if [[ ${{#COMPREPLY[@]}} -eq 1 && ${{COMPREPLY[0]}} == *: ]]; then
        compopt -o nospace 2>/dev/null
    fi
}}

_lssh() {{
    local cur=${{COMP_WORDS[COMP_CWORD]}} prev=${{COMP_WORDS[COMP_CWORD-1]}}
    local cmd=${{COMP_WORDS[1]}} opts
    COMPREPLY=()

    if [[ $COMP_CWORD -eq 1 ]]; then
        COMPREPLY=($(compgen -W "{commands} $(_lssh_servers)" -- "$cur"))
        return
    fi

    case $prev in
        --key|-k) COMPREPLY=($(compgen -f -- "$cur")); return ;;
    esac

    if [[ $cur == -* ]]; then
        case $cmd in
{option_cases}            *) opts="{connect_options}" ;;
        esac
        COMPREPLY=($(compgen -W "$opts" -- "$cur"))
        return
    fi

    case $cmd in
{argument_cases}    esac
}}

complete -F _lssh lssh
"#,
        commands = all_command_words(),
        connect_options = option_words(connect_spec()),
    )
}

/// Quote for a zsh or bash single-quoted string.
fn single_quote(text: &str) -> String {
    format!("'{}'", text.replace('\'', r"'\''"))
}

fn zsh() -> String {
    let mut descriptions = String::new();
    let mut cases = String::new();
    for spec in COMMANDS {
        for name in names(spec) {
            descriptions.push_str(&format!(
                "    {}\n",
                single_quote(&format!("{name}:{}", spec.about))
            ));
        }
        cases.push_str(&format!("    ({})\n", names(spec).join("|")));
        let mut specs = zsh_option_specs(spec);
        let argument = match spec.completes {
            Complete::Nothing => None,
            Complete::Server => Some("'1:server:_lssh_servers'".to_string()),
            Complete::Servers => Some("'1:servers:_lssh_server_list'".to_string()),
            Complete::RemotePath => Some("'*:path:_lssh_remote_path'".to_string()),
            Complete::File => Some("'*:file:_files'".to_string()),
            Complete::Command => Some(format!("'1:command:({})'", all_command_words())),
            Complete::Choices(choices) => Some(format!("'1:argument:({})'", choices.join(" "))),
        };
        specs.extend(argument);
        if specs.is_empty() {
            cases.push_str("      :\n      ;;\n");
        } else {
            cases.push_str(&format!(
                "      _arguments -s \\\n        {}\n      ;;\n",
                specs.join(" \\\n        ")
            ));
        }
    }
    let connect_options = zsh_option_specs(connect_spec()).join(" ");

    format!(
        r#"#compdef lssh
# zsh completion for lssh (generated by `lssh completions zsh`)

_lssh_servers() {{
  local -a servers
  servers=(${{(f)"$(lssh list --names 2>/dev/null)"}})
  _describe -t servers 'server' servers
}}

# A comma-separated list of servers, or "all".
_lssh_server_list() {{
  local -a servers
  servers=(${{(f)"$(lssh list --names 2>/dev/null)"}} all)
  _values -s , 'servers' $servers
}}

# <server>:<path> or a local path.
_lssh_remote_path() {{
  local -a servers
  servers=(${{(f)"$(lssh list --names 2>/dev/null)"}})
  compadd -S '' -- ${{^servers}}:
  _files
}}

_lssh() {{
  local -a commands
  commands=(
{descriptions}  )

  if (( CURRENT == 2 )); then
    _describe -t commands 'command' commands
    _lssh_servers
    return
  fi

  shift words
  (( CURRENT-- ))
  case $words[1] in
{cases}    (*)
      _arguments -s {connect_options}
      ;;
  esac
}}

if [ "$funcstack[1]" = "_lssh" ]; then
  _lssh "$@"
else
  compdef _lssh lssh
fi
"#
    )
}

fn zsh_option_specs(spec: &Spec) -> Vec<String> {
    spec.options
        .iter()
        .map(|opt| {
            let about = opt.about.replace('[', "\\[").replace(']', "\\]");
            let value = match opt.value {
                Some(_) => ":file:_files",
                None => "",
            };
            match opt.short {
                Some(short) => format!(
                    "'(-{short} {long})'{{-{short},{long}}}{}",
                    single_quote(&format!("[{about}]{value}")),
                    long = opt.long
                ),
                None => single_quote(&format!("{}[{about}]{value}", opt.long)),
            }
        })
        .collect()
}

/// Quote for a fish single-quoted string.
fn fish_quote(text: &str) -> String {
    format!("'{}'", text.replace('\\', "\\\\").replace('\'', "\\'"))
}

fn fish() -> String {
    let mut lines = Vec::new();
    for spec in COMMANDS {
        for name in names(spec) {
            lines.push(format!(
                "complete -c lssh -n __lssh_no_command -a {name} -d {}",
                fish_quote(spec.about)
            ));
        }
    }
    lines.push(String::new());
    for spec in COMMANDS {
        let condition = fish_quote(&format!("__lssh_command_is {}", names(spec).join(" ")));
        let argument = match spec.completes {
            Complete::Nothing => None,
            Complete::Server => Some("-a '(__lssh_servers)'".to_string()),
            Complete::Servers => Some("-a '(__lssh_servers) all'".to_string()),
            Complete::RemotePath => Some("-F -a '(__lssh_remote_prefixes)'".to_string()),
            Complete::File => Some("-F".to_string()),
            Complete::Command => Some(format!("-a {}", fish_quote(&all_command_words()))),
            Complete::Choices(choices) => Some(format!("-a {}", fish_quote(&choices.join(" ")))),
        };
        if let Some(argument) = argument {
            lines.push(format!("complete -c lssh -n {condition} {argument}"));
        }
        for opt in spec.options {
            let mut line = format!(
                "complete -c lssh -n {condition} -l {}",
                opt.long.trim_start_matches("--")
            );
            if let Some(short) = opt.short {
                line.push_str(&format!(" -s {short}"));
            }
            if opt.value.is_some() {
                line.push_str(" -r -F");
            }
            line.push_str(&format!(" -d {}", fish_quote(opt.about)));
            lines.push(line);
        }
    }

    format!(
        r#"# fish completion for lssh (generated by `lssh completions fish`)

function __lssh_servers
    lssh list --names 2>/dev/null
end

function __lssh_remote_prefixes
    for server in (__lssh_servers)
        echo $server:
    end
end

function __lssh_no_command
    test (count (commandline -opc)) -eq 1
end

function __lssh_command_is
    set -l words (commandline -opc)
    test (count $words) -ge 2; and contains -- $words[2] $argv
end

complete -c lssh -f
complete -c lssh -n __lssh_no_command -a '(__lssh_servers)' -d server
{}
"#,
        lines.join("\n")
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_shell_knows_every_command() {
        for shell in ["bash", "zsh", "fish"] {
            let script = script(shell).unwrap();
            for spec in COMMANDS {
                assert!(script.contains(spec.name), "{shell} misses {}", spec.name);
            }
            assert!(script.contains("lssh list --names"), "{shell}");
        }
        assert!(script("powershell").is_err());
    }

    #[test]
    fn quoting() {
        assert_eq!(single_quote("it's"), r"'it'\''s'");
        assert_eq!(fish_quote("it's"), r"'it\'s'");
    }
}
